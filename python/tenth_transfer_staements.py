#Transfer statements/jumping statements
#pass statement-it does nothing , to avoid errors we can add pass program
for i in range(5):
    pass

#break statement-the program exits whien we put break
for i in range (5):
    if i==2:
        break
    print(i)

#continue statement-the programs just skips the particular part and then continues 
for i in range (5):
    if i==2:
        continue
    print(i)

